"""Dataset-mode labels and citation text shown wherever results are displayed."""

from __future__ import annotations

from typing import Any

from threatgraph.config import DatasetMode

PIPELINE_VERSION = "0.1.0"

LANL_CITATION = (
    'A. D. Kent, "Comprehensive, Multi-Source Cyber-Security Events," Los Alamos National '
    "Laboratory, http://dx.doi.org/10.17021/1179829, 2015."
)
LANL_URL = "https://csr.lanl.gov/data/cyber1/"

MODE_LABELS: dict[str, str] = {
    "synthetic": "Synthetic demo",
    "lanl": "LANL 2015 (real, de-identified)",
}

LABEL_SOURCES: dict[str, str] = {
    "synthetic": "synthetic_redteam",
    "lanl": "lanl_redteam",
}

LABEL_SEMANTICS = (
    "A window is 'known red-team' if it contains at least one authentication event matched to "
    "the red-team file. All other windows are 'unlabeled', not confirmed benign: the red-team "
    "file documents some known malicious authentications, not every malicious event."
)


def mode_label(mode: DatasetMode) -> str:
    return MODE_LABELS[mode]


def label_source(mode: DatasetMode) -> str:
    return LABEL_SOURCES[mode]


def provenance_block(dataset: str, mode: DatasetMode, config_hash: str) -> dict[str, Any]:
    source = (
        "Deterministic synthetic fixture generated by scripts/generate_demo_data.py "
        "in LANL-compatible format. Not real network activity."
        if mode == "synthetic"
        else f"{LANL_CITATION} Historical research data, not live threat intelligence."
    )
    return {
        "dataset": dataset,
        "mode": mode,
        "mode_label": mode_label(mode),
        "is_synthetic": mode == "synthetic",
        "source": source,
        "source_url": None if mode == "synthetic" else LANL_URL,
        "label_source": label_source(mode),
        "config_hash": config_hash,
        "pipeline_version": PIPELINE_VERSION,
    }
