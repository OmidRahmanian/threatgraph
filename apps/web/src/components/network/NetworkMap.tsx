"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import { useMemo, useState } from "react";
import { api, useLoad } from "@/lib/data";
import { int, relTime, score as fmtScore } from "@/lib/format";
import { buildView, searchNodes, type AccountView, type ComputerView, type MapView, type ShowMode } from "@/lib/networkMap";
import type { EvalSplit, IncidentIndex, ModelList, NetworkMap as NetworkMapData } from "@/lib/types";
import { EntityPanel } from "../explorer/EvidencePanel";
import { AlertBadge, Callout, ErrorBlock, KnownRedteamBadge, LoadingBlock, Panel, ProvenanceBadge, SectionTitle, Segmented, UnlabeledBadge } from "../ui";
import { MapCanvas } from "./MapCanvas";

function readQuery() {
  if (typeof window === "undefined") return new URLSearchParams();
  return new URLSearchParams(window.location.search);
}

const explorerHref = (windowId: string, modelId: string) =>
  `/threatgraph/explorer/?${new URLSearchParams({ window: windowId, model: modelId })}`;

export function NetworkMap() {
  const [split, setSplit] = useState<EvalSplit>(() => (readQuery().get("split") === "validation" ? "validation" : "test"));
  const base = useLoad(() => Promise.all([api.models(), api.incidents()]), "network-base");
  const map = useLoad(() => api.network(split), `network-${split}`);
  if (base.status === "error") return <ErrorBlock error={base.error} />;
  if (map.status === "error") return <ErrorBlock error={map.error} />;
  return (
    <div className="space-y-6 fade-in">
      <header className="space-y-3">
        <div className="flex flex-wrap items-center gap-3">
          <h1 className="text-2xl font-semibold tracking-tight">Network map</h1>
          {map.status === "ready" ? <ProvenanceBadge provenance={map.data.provenance} /> : null}
        </div>
        <p className="max-w-3xl text-sm leading-relaxed text-ink-2">
          Every account a model flagged in the split, and every account with known red-team activity, drawn with the computers it
          authenticated from or to. Computers shared by several of these accounts sit between them. A blue ring is a model alert
          (an unusual hour); an orange diamond comes from the red-team file. Neither proves the rest of the picture is benign or
          malicious.
        </p>
        {map.status === "ready" && map.data.provenance.is_synthetic ? (
          <Callout title="Synthetic demo" tone="synthetic">
            Accounts, computers and red-team campaigns here were generated by scripts/generate_demo_data.py. No real network
            activity is shown.
          </Callout>
        ) : null}
      </header>
      {base.status === "loading" || map.status === "loading" ? (
        <LoadingBlock label="Loading network map…" />
      ) : (
        <MapBody key={split} map={map.data} models={base.data[0]} incidents={base.data[1]} split={split} onSplit={setSplit} />
      )}
    </div>
  );
}

function MapBody({
  map,
  models,
  incidents,
  split,
  onSplit,
}: {
  map: NetworkMapData;
  models: ModelList;
  incidents: IncidentIndex;
  split: EvalSplit;
  onSplit: (s: EvalSplit) => void;
}) {
  const [query] = useState(readQuery);
  const modelIds = models.models.map((m) => m.model_id);
  const [modelId, setModelId] = useState(() => {
    const q = query.get("model");
    return q && modelIds.includes(q) ? q : modelIds.at(-1)!;
  });
  const [show, setShow] = useState<ShowMode>("all");
  const [from, setFrom] = useState(map.days[0]);
  const [to, setTo] = useState(map.days.at(-1)!);
  const [selected, setSelected] = useState<string | null>(() => query.get("node"));
  const [focus, setFocus] = useState<{ id: string; seq: number } | null>(() => {
    const node = query.get("node");
    return node ? { id: node, seq: 1 } : null;
  });
  const [search, setSearch] = useState("");

  const view = useMemo(() => buildView(map, { modelId, show, from, to }), [map, modelId, show, from, to]);
  const modelName = models.models.find((m) => m.model_id === modelId)?.display_name ?? modelId;
  const hits = useMemo(() => searchNodes(view, search), [view, search]);
  const incidentsByAccount = useMemo(() => {
    const out = new Map<string, string[]>();
    for (const i of incidents.incidents) out.set(i.principal_id, [...(out.get(i.principal_id) ?? []), i.incident_id]);
    return out;
  }, [incidents]);

  const select = (id: string | null, center = false) => {
    setSelected(id);
    if (id && center) setFocus((f) => ({ id, seq: (f?.seq ?? 0) + 1 }));
    const q = new URLSearchParams({ split, model: modelId, ...(id ? { node: id } : {}) });
    window.history.replaceState(null, "", `${window.location.pathname}?${q}`);
  };
  const account = view.accounts.find((a) => a.id === selected);
  const computer = view.computers.find((c) => c.id === selected);
  const alertedAccounts = view.accounts.filter((a) => a.alerts > 0).length;
  const redteamAccounts = view.accounts.filter((a) => a.redteamWindows > 0).length;
  const truncated = map.accounts.filter((a) => a.n_computers_total > a.n_computers_shown);
  const dayLabel = (d: number) => `Day ${d}`;

  return (
    <>
      <Panel>
        <div className="flex flex-wrap items-end gap-x-5 gap-y-3">
          <Field label="Split">
            <Segmented
              label="Split"
              value={split}
              onChange={onSplit}
              options={[
                { value: "validation", label: "Validation" },
                { value: "test", label: "Test" },
              ]}
            />
          </Field>
          <Field label="Alerts by">
            <select
              value={modelId}
              onChange={(e) => setModelId(e.target.value)}
              className="block rounded-md border border-line bg-panel px-2 py-1.5 text-sm text-ink"
              data-testid="map-model"
            >
              {models.models.map((m) => (
                <option key={m.model_id} value={m.model_id}>
                  {m.display_name}
                </option>
              ))}
            </select>
          </Field>
          <Field label="Accounts">
            <Segmented
              label="Accounts shown"
              value={show}
              onChange={setShow}
              options={[
                { value: "all", label: "All mapped" },
                { value: "alerted", label: "Alerted" },
                { value: "redteam", label: "Red-team" },
              ]}
            />
          </Field>
          <Field label="Days">
            <div className="flex items-center gap-1.5">
              <select
                aria-label="From day"
                value={from}
                onChange={(e) => {
                  const v = Number(e.target.value);
                  setFrom(v);
                  if (v > to) setTo(v);
                }}
                className="rounded-md border border-line bg-panel px-2 py-1.5 text-sm text-ink"
                data-testid="map-from"
              >
                {map.days.map((d) => (
                  <option key={d} value={d}>
                    {dayLabel(d)}
                  </option>
                ))}
              </select>
              <span className="text-ink-3">–</span>
              <select
                aria-label="To day"
                value={to}
                onChange={(e) => {
                  const v = Number(e.target.value);
                  setTo(v);
                  if (v < from) setFrom(v);
                }}
                className="rounded-md border border-line bg-panel px-2 py-1.5 text-sm text-ink"
                data-testid="map-to"
              >
                {map.days.map((d) => (
                  <option key={d} value={d}>
                    {dayLabel(d)}
                  </option>
                ))}
              </select>
            </div>
          </Field>
          <Field label="Find an account or computer">
            <div className="relative">
              <input
                type="search"
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter" && hits[0]) {
                    select(hits[0].id, true);
                    setSearch("");
                  }
                }}
                placeholder="e.g. U12 or C42"
                className="w-56 rounded-md border border-line bg-panel px-2 py-1.5 text-sm text-ink placeholder:text-ink-3"
                aria-label="Find an account or computer on the map"
                data-testid="map-search"
              />
              {search && (
                <ul className="absolute z-20 mt-1 w-56 overflow-hidden rounded-md border border-line bg-panel shadow-sm" data-testid="map-search-results">
                  {hits.length === 0 ? <li className="px-2 py-1.5 text-xs text-ink-3">Not on the map with these filters</li> : null}
                  {hits.map((h) => (
                    <li key={h.id}>
                      <button
                        className="flex w-full items-center justify-between gap-2 px-2 py-1.5 text-left text-sm hover:bg-panel-2"
                        onClick={() => {
                          select(h.id, true);
                          setSearch("");
                        }}
                      >
                        <span className="truncate font-mono text-ink">{h.label}</span>
                        <span className="text-xs text-ink-3">{h.kind}</span>
                      </button>
                    </li>
                  ))}
                </ul>
              )}
            </div>
          </Field>
        </div>
        <p className="mt-4 text-xs text-ink-3 tabular-nums" data-testid="map-counts">
          {view.accounts.length} accounts ({alertedAccounts} alerted by {modelName}, {redteamAccounts} with known red-team windows) ·{" "}
          {view.computers.length} computers · {view.links.length} links · {dayLabel(from)}
          {from !== to ? `–${to}` : ""}
        </p>
      </Panel>

      <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_340px]">
        <div className="min-w-0 space-y-3">
          <MapCanvas view={view} modelName={modelName} selected={selected} onSelect={(id) => select(id)} focus={focus} />
          <Legend modelName={modelName} />
        </div>
        <Panel className="self-start" id="map-detail">
          {account ? (
            <AccountDetail
              a={account}
              view={view}
              modelId={modelId}
              from={from}
              to={to}
              incidents={incidentsByAccount.get(account.id) ?? []}
              onSelect={(id) => select(id, true)}
            />
          ) : computer ? (
            <ComputerDetail c={computer} view={view} onSelect={(id) => select(id, true)} />
          ) : (
            <div className="space-y-2 text-sm text-ink-2" data-testid="map-detail-empty">
              <SectionTitle title="Details" />
              <p>Select an account or a computer on the map, or find one by name.</p>
              <p className="text-xs text-ink-3">Hover a node to light up what it is connected to.</p>
            </div>
          )}
        </Panel>
      </div>

      <Panel>
        <SectionTitle title="What is on the map" />
        <ul className="list-disc space-y-1 pl-5 text-xs text-ink-2">
          <li>
            {map.selection}. {map.n_accounts_selected} of {map.n_accounts_in_split} accounts active in the split qualify;{" "}
            {map.accounts.length} are mapped.
          </li>
          <li>
            Each account shows up to {map.max_computers_per_account} computers, ordered by {map.computer_order}.
            {truncated.length
              ? ` ${truncated.length} account${truncated.length === 1 ? " has" : "s have"} more: ${truncated
                  .map((a) => `${a.label} (${a.n_computers_shown} of ${a.n_computers_total})`)
                  .join(", ")}.`
              : " No account exceeds that."}
          </li>
          <li>{map.semantics}</li>
        </ul>
        <AccountTable view={view} modelName={modelName} selected={selected} onSelect={(id) => select(id, true)} />
      </Panel>
    </>
  );
}

function Field({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="space-y-1">
      <div className="text-xs text-ink-3">{label}</div>
      {children}
    </div>
  );
}

function AccountDetail({
  a,
  view,
  modelId,
  from,
  to,
  incidents,
  onSelect,
}: {
  a: AccountView;
  view: MapView;
  modelId: string;
  from: number;
  to: number;
  incidents: string[];
  onSelect: (id: string) => void;
}) {
  const router = useRouter();
  const windows = a.account.windows.filter((w) => w.day >= from && w.day <= to);
  const links = view.links.filter((l) => l.account === a.id).sort((x, y) => y.knownRedteam - x.knownRedteam || y.events - x.events);
  const label = new Map(view.computers.map((c) => [c.id, c.label]));
  const s = a.account.scores[modelId];
  return (
    <div className="space-y-4 fade-in" data-testid="map-account-detail">
      <div className="flex flex-wrap items-center gap-2">
        <span className="rounded-full border border-line px-2 py-0.5 text-xs text-ink-3">Account</span>
        <span className="font-mono text-sm text-ink">{a.label}</span>
        <AlertBadge flagged={a.alerts > 0} />
        {a.redteamWindows ? <KnownRedteamBadge count={a.redteamWindows} /> : <UnlabeledBadge />}
      </div>
      <dl className="grid grid-cols-2 gap-x-4 gap-y-2 text-sm">
        <Fact k="Alerts in range" v={int(a.alerts)} />
        <Fact k="Highest score in split" v={`${fmtScore(s.max_score)} (rank ${s.best_rank})`} />
        <Fact k="Windows in split" v={int(a.account.n_windows)} />
        <Fact k="Computers in range" v={`${a.degree}${a.account.n_computers_total > a.account.n_computers_shown ? ` (map cap; ${a.account.n_computers_total} in split)` : ""}`} />
      </dl>
      {incidents.length ? (
        <div className="flex flex-wrap gap-2">
          {incidents.map((id) => (
            <Link
              key={id}
              href={`/threatgraph/replay/?${new URLSearchParams({ incident: id })}`}
              className="rounded-md border border-redteam px-2.5 py-1 text-xs text-ink hover:bg-redteam-soft"
              data-testid="map-replay-link"
            >
              Replay red-team incident →
            </Link>
          ))}
        </div>
      ) : null}
      <div>
        <h3 className="text-sm font-medium text-ink">Alerted or red-team windows in range</h3>
        {windows.length === 0 ? (
          <p className="mt-1 text-xs text-ink-3">None in the selected days.</p>
        ) : (
          <ul className="mt-2 space-y-1.5" data-testid="map-windows">
            {windows.map((w) => (
              <li key={w.window_id}>
                <Link
                  href={explorerHref(w.window_id, modelId)}
                  className="flex flex-wrap items-center gap-1.5 rounded-md border border-line px-2 py-1.5 text-xs hover:bg-panel-2"
                >
                  <span className="text-ink-2">{relTime(w.window_start)}</span>
                  <span className="font-mono text-ink-3">{fmtScore(w.scores[modelId].score)}</span>
                  {w.scores[modelId].flagged ? <AlertBadge flagged /> : null}
                  {w.known_redteam ? <KnownRedteamBadge /> : null}
                  <span className="ml-auto text-ink-3">Explore hour →</span>
                </Link>
              </li>
            ))}
          </ul>
        )}
      </div>
      <div>
        <h3 className="text-sm font-medium text-ink">Computers in range</h3>
        <ul className="mt-2 max-h-56 space-y-1 overflow-auto text-xs" data-testid="map-account-links">
          {links.map((l) => (
            <li key={l.id} className="flex items-center justify-between gap-2">
              <button className="font-mono text-ink underline decoration-line underline-offset-2" onClick={() => onSelect(l.computer)}>
                {label.get(l.computer)}
              </button>
              <span className="text-ink-3 tabular-nums">
                {l.link.role} · {int(l.events)} ev{l.knownRedteam ? <span className="text-redteam"> · {l.knownRedteam} red-team</span> : null}
              </span>
            </li>
          ))}
        </ul>
      </div>
      <details className="rounded-lg border border-line">
        <summary className="cursor-pointer px-3 py-2 text-sm text-ink-2">Full entity profile</summary>
        <div className="border-t border-line p-3">
          <EntityPanel
            entityId={a.id}
            onEntity={onSelect}
            onWindow={(id) => router.push(explorerHref(id, modelId))}
            windowIds={new Set(a.account.windows.map((w) => w.window_id))}
          />
        </div>
      </details>
    </div>
  );
}

function ComputerDetail({ c, view, onSelect }: { c: ComputerView; view: MapView; onSelect: (id: string) => void }) {
  const links = view.links.filter((l) => l.computer === c.id).sort((x, y) => y.knownRedteam - x.knownRedteam || y.events - x.events);
  const label = new Map(view.accounts.map((a) => [a.id, a.label]));
  return (
    <div className="space-y-4 fade-in" data-testid="map-computer-detail">
      <div className="flex flex-wrap items-center gap-2">
        <span className="rounded-full border border-line px-2 py-0.5 text-xs text-ink-3">Computer</span>
        <span className="font-mono text-sm text-ink">{c.label}</span>
        {c.knownRedteam ? <KnownRedteamBadge count={c.knownRedteam} /> : null}
      </div>
      <dl className="grid grid-cols-2 gap-x-4 gap-y-2 text-sm">
        <Fact k="Mapped accounts in range" v={int(c.degree)} />
        <Fact k="Accounts in the split" v={int(c.computer.n_accounts_in_split)} />
        <Fact k="Events on mapped links" v={int(c.events)} />
        <Fact k="Known red-team events" v={int(c.knownRedteam)} />
      </dl>
      <div>
        <h3 className="text-sm font-medium text-ink">Mapped accounts</h3>
        <ul className="mt-2 max-h-56 space-y-1 overflow-auto text-xs" data-testid="map-computer-links">
          {links.map((l) => (
            <li key={l.id} className="flex items-center justify-between gap-2">
              <button className="font-mono text-ink underline decoration-line underline-offset-2" onClick={() => onSelect(l.account)}>
                {label.get(l.account)}
              </button>
              <span className="text-ink-3 tabular-nums">
                {l.link.role} · {int(l.events)} ev{l.alerted ? " · alerted" : ""}
                {l.knownRedteam ? <span className="text-redteam"> · {l.knownRedteam} red-team</span> : null}
              </span>
            </li>
          ))}
        </ul>
      </div>
      <details className="rounded-lg border border-line">
        <summary className="cursor-pointer px-3 py-2 text-sm text-ink-2">Full entity profile</summary>
        <div className="border-t border-line p-3">
          <EntityPanel entityId={c.id} onEntity={onSelect} onWindow={() => {}} windowIds={new Set()} />
        </div>
      </details>
    </div>
  );
}

function Fact({ k, v }: { k: string; v: React.ReactNode }) {
  return (
    <div>
      <dt className="text-xs text-ink-3">{k}</dt>
      <dd className="text-ink-2 tabular-nums">{v}</dd>
    </div>
  );
}

function Legend({ modelName }: { modelName: string }) {
  const item = (svg: React.ReactNode, text: string) => (
    <li className="flex items-center gap-2">
      <svg aria-hidden width="30" height="22" viewBox="0 0 30 22">
        {svg}
      </svg>
      {text}
    </li>
  );
  return (
    <ul className="flex flex-wrap gap-x-5 gap-y-2 text-xs text-ink-2" aria-label="Map legend">
      {item(<circle cx="15" cy="11" r="7" fill="var(--ink-2)" />, "Account")}
      {item(<rect x="10" y="6" width="10" height="10" rx="1.5" fill="var(--ink-3)" fillOpacity="0.7" />, "Computer (larger = shared by more mapped accounts)")}
      {item(
        <>
          <circle cx="15" cy="11" r="6" fill="var(--ink-2)" />
          <circle cx="15" cy="11" r="9" fill="none" stroke="var(--model)" strokeWidth="2.2" />
        </>,
        `Alerted by ${modelName} in the selected days`,
      )}
      {item(<line x1="2" y1="11" x2="28" y2="11" stroke="var(--model)" strokeWidth="1.6" />, "Link active in an alerted window")}
      {item(
        <>
          <line x1="2" y1="11" x2="28" y2="11" stroke="var(--redteam)" strokeWidth="2" />
          <path d="M15,5 L21,11 L15,17 L9,11 Z" fill="var(--redteam)" />
        </>,
        "Known red-team events (label from the red-team file)",
      )}
      {item(<line x1="2" y1="11" x2="28" y2="11" stroke="var(--ink-3)" strokeWidth="1" strokeOpacity="0.6" />, "Other authentication")}
    </ul>
  );
}

function AccountTable({
  view,
  modelName,
  selected,
  onSelect,
}: {
  view: MapView;
  modelName: string;
  selected: string | null;
  onSelect: (id: string) => void;
}) {
  const rows = [...view.accounts].sort((a, b) => b.redteamWindows - a.redteamWindows || b.alerts - a.alerts || a.label.localeCompare(b.label));
  return (
    <details className="mt-4 rounded-lg border border-line">
      <summary className="cursor-pointer px-3 py-2 text-sm text-ink-2">Table view · {view.accounts.length} accounts</summary>
      <div className="max-h-96 overflow-auto">
        <table className="w-full text-left text-xs tabular-nums" data-testid="map-table">
          <thead className="sticky top-0 bg-panel text-ink-3">
            <tr>
              <th className="px-3 py-1.5 font-normal">Account</th>
              <th className="px-3 py-1.5 text-right font-normal">{modelName} alerts</th>
              <th className="px-3 py-1.5 text-right font-normal">Known red-team windows</th>
              <th className="px-3 py-1.5 text-right font-normal">Computers</th>
              <th className="px-3 py-1.5 text-right font-normal">Events</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((a) => (
              <tr key={a.id} className={`border-t border-line ${a.id === selected ? "bg-panel-2" : ""}`}>
                <td className="px-3 py-1.5">
                  <button className="font-mono text-ink underline decoration-line underline-offset-2" onClick={() => onSelect(a.id)}>
                    {a.label}
                  </button>
                </td>
                <td className="px-3 py-1.5 text-right">{a.alerts || "—"}</td>
                <td className="px-3 py-1.5 text-right">{a.redteamWindows || "—"}</td>
                <td className="px-3 py-1.5 text-right">{a.degree}</td>
                <td className="px-3 py-1.5 text-right">{int(a.events)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </details>
  );
}
