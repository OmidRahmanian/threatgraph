"use client";

import { useMemo, useState } from "react";
import { api, useLoad } from "@/lib/data";
import { int, relTime, score as fmtScore, windowLabel } from "@/lib/format";
import type { GraphWindowIndex, GraphWindowSummary, ModelList } from "@/lib/types";
import {
  AlertBadge,
  Callout,
  ErrorBlock,
  KnownRedteamBadge,
  LoadingBlock,
  Panel,
  ProvenanceBadge,
  SectionTitle,
  Segmented,
  UnlabeledBadge,
} from "../ui";
import { EdgeEvidence, EntityPanel } from "./EvidencePanel";
import { GraphView, groupEdges, type Selection } from "./GraphView";

type Filter = "alerts" | "known" | "all";

function readQuery(): { window: string | null; model: string | null } {
  if (typeof window === "undefined") return { window: null, model: null };
  const q = new URLSearchParams(window.location.search);
  return { window: q.get("window"), model: q.get("model") };
}

export function Explorer() {
  const base = useLoad(() => Promise.all([api.graphIndex("test"), api.models()]), "explorer-base");
  if (base.status === "loading") return <LoadingBlock label="Loading alert windows…" />;
  if (base.status === "error") return <ErrorBlock error={base.error} />;
  return <ExplorerBody index={base.data[0]} models={base.data[1]} />;
}

function ExplorerBody({ index, models }: { index: GraphWindowIndex; models: ModelList }) {
  const [query] = useState(readQuery);
  const modelIds = models.models.map((m) => m.model_id);
  const [modelId, setModelId] = useState(query.model && modelIds.includes(query.model) ? query.model : modelIds.at(-1)!);
  const [filter, setFilter] = useState<Filter>("alerts");
  const [selected, setSelected] = useState<string | null>(query.window);

  const list = useMemo(() => {
    const rows = index.windows.filter((w) =>
      filter === "all" ? true : filter === "known" ? w.label === "known_redteam" : w.scores[modelId]?.flagged,
    );
    return rows.sort((a, b) => a.scores[modelId].rank - b.scores[modelId].rank);
  }, [index, filter, modelId]);
  const active = selected ?? list[0]?.window_id ?? null;
  const windowIds = useMemo(() => new Set(index.windows.map((w) => w.window_id)), [index]);

  const choose = (id: string) => {
    setSelected(id);
    const q = new URLSearchParams({ window: id, model: modelId });
    window.history.replaceState(null, "", `${window.location.pathname}?${q}`);
  };

  return (
    <div className="space-y-6 fade-in">
      <header className="space-y-3">
        <div className="flex flex-wrap items-center gap-3">
          <h1 className="text-2xl font-semibold tracking-tight">Network explorer</h1>
          <ProvenanceBadge provenance={index.provenance} />
        </div>
        <p className="max-w-3xl text-sm leading-relaxed text-ink-2">
          Pick a held-out test window. The graph shows the computers that account authenticated between in that hour, as
          recorded, plus other accounts&apos; activity on the same computers. Every edge links to the events behind it. A model
          alert means the hour was unusual; only the red-team file marks activity as known malicious.
        </p>
        {index.provenance.is_synthetic ? (
          <Callout title="Synthetic demo" tone="synthetic">
            Accounts, computers and red-team campaigns here were generated by scripts/generate_demo_data.py. No real network
            activity is shown.
          </Callout>
        ) : null}
      </header>

      <div className="grid gap-6 lg:grid-cols-[300px_minmax(0,1fr)]">
        <Panel className="self-start">
          <SectionTitle title="Windows" subtitle={index.selection} />
          <div className="space-y-3">
            <label className="block text-xs text-ink-3">
              Rank and alert by
              <select
                value={modelId}
                onChange={(e) => setModelId(e.target.value)}
                className="mt-1 block w-full rounded-md border border-line bg-panel px-2 py-1.5 text-sm text-ink"
                data-testid="explorer-model"
              >
                {models.models.map((m) => (
                  <option key={m.model_id} value={m.model_id}>
                    {m.display_name}
                  </option>
                ))}
              </select>
            </label>
            <Segmented
              label="Window filter"
              value={filter}
              onChange={setFilter}
              options={[
                { value: "alerts", label: "Alerts" },
                { value: "known", label: "Red-team" },
                { value: "all", label: "All" },
              ]}
            />
            <ul className="max-h-[640px] divide-y divide-line overflow-auto rounded-lg border border-line" data-testid="window-list">
              {list.length === 0 ? <li className="px-3 py-3 text-sm text-ink-3">No windows match this filter.</li> : null}
              {list.map((w) => (
                <WindowItem key={w.window_id} w={w} modelId={modelId} active={w.window_id === active} onClick={() => choose(w.window_id)} />
              ))}
            </ul>
          </div>
        </Panel>
        <div className="min-w-0 space-y-6">
          {active ? (
            <WindowGraph key={active} windowId={active} modelId={modelId} windowIds={windowIds} onWindow={choose} />
          ) : (
            <Panel>
              <p className="text-sm text-ink-3">Select a window.</p>
            </Panel>
          )}
        </div>
      </div>
    </div>
  );
}

function WindowItem({ w, modelId, active, onClick }: { w: GraphWindowSummary; modelId: string; active: boolean; onClick: () => void }) {
  const s = w.scores[modelId];
  return (
    <li>
      <button onClick={onClick} aria-pressed={active} className={`flex w-full flex-col gap-1 px-3 py-2 text-left hover:bg-panel-2 ${active ? "bg-panel-2" : ""}`}>
        <div className="flex items-center justify-between gap-2">
          <span className="truncate font-mono text-xs text-ink">
            #{s.rank} · {w.principal}
          </span>
          <span className="font-mono text-xs text-ink-2">{fmtScore(s.score)}</span>
        </div>
        <div className="flex flex-wrap items-center gap-1.5">
          <span className="text-xs text-ink-3">{relTime(w.window_start)}</span>
          <AlertBadge flagged={s.flagged} />
          {w.label === "known_redteam" ? <KnownRedteamBadge count={w.n_labeled_events} /> : <UnlabeledBadge />}
        </div>
      </button>
    </li>
  );
}

function WindowGraph({
  windowId,
  modelId,
  windowIds,
  onWindow,
}: {
  windowId: string;
  modelId: string;
  windowIds: Set<string>;
  onWindow: (id: string) => void;
}) {
  const state = useLoad(() => api.graphWindow(windowId), windowId);
  const [showHop2, setShowHop2] = useState(false);
  const [selection, setSelection] = useState<Selection>(null);
  if (state.status === "loading") return <LoadingBlock label="Loading graph…" />;
  if (state.status === "error") return <ErrorBlock error={state.error} />;
  if (!state.data) {
    return (
      <Panel>
        <p className="text-sm text-ink-2" data-testid="graph-unavailable">
          This window&apos;s graph is not in the static export, which covers each model&apos;s top test windows and every known
          red-team test window. Run the API to explore any window.
        </p>
      </Panel>
    );
  }
  const { window: w, graph } = state.data;
  const s = w.scores[modelId];
  const nodes = new Map(graph.nodes.map((n) => [n.node_id, n]));
  const { groups } = groupEdges(graph.edges.filter((e) => e.hop <= (showHop2 ? 2 : 1)));
  const group = selection?.kind === "edge" ? groups.find((g) => g.key === selection.key) : undefined;
  const hop1 = graph.edges.filter((e) => e.hop === 1);
  return (
    <>
      <Panel>
        <SectionTitle
          title={`${w.principal} · ${windowLabel(w.window_start, w.window_end)}`}
          subtitle={
            <>
              Score {fmtScore(s.score)} vs threshold {fmtScore(s.threshold)} · rank {s.rank} in the test split ·{" "}
              {int(hop1.reduce((a, e) => a + e.n_events, 0))} in-scope events by this account
            </>
          }
          right={
            <div className="flex flex-wrap items-center gap-2">
              <AlertBadge flagged={s.flagged} />
              {w.label === "known_redteam" ? <KnownRedteamBadge count={w.n_labeled_events} /> : <UnlabeledBadge />}
            </div>
          }
        />
        <div className="mb-3 flex flex-wrap items-center justify-between gap-3 text-xs text-ink-3">
          <label className="flex items-center gap-2 text-sm text-ink-2">
            <input type="checkbox" checked={showHop2} onChange={(e) => {
                setShowHop2(e.target.checked);
                setSelection(null);
              }} data-testid="toggle-hop2" />
            Show other accounts on these computers (hop 2)
          </label>
          <span data-testid="edge-count">
            {hop1.length} edges by this account
            {showHop2
              ? ` · ${graph.edges.length - hop1.length} by other accounts shown${
                  graph.truncated ? ` (${graph.n_edges_total} in total, capped at ${graph.max_edges}; order: ${graph.truncation_order})` : ""
                }`
              : ""}
          </span>
        </div>
        <GraphView graph={graph} showHop2={showHop2} selection={selection} onSelect={setSelection} />
        <p className="mt-3 text-xs text-ink-3">
          {graph.semantics} Hubs: more than {graph.hub_max_principals} accounts in this window.
        </p>
      </Panel>
      <Panel id="evidence">
        <SectionTitle title="Evidence" subtitle="Select an edge or a computer in the graph, or an account in an edge." />
        {group ? (
          <EdgeEvidence group={group} nodes={nodes} onEntity={(id) => setSelection({ kind: "node", id })} />
        ) : selection?.kind === "node" ? (
          <EntityPanel
            key={selection.id}
            entityId={selection.id}
            onEntity={(id) => setSelection({ kind: "node", id })}
            onWindow={onWindow}
            windowIds={windowIds}
          />
        ) : (
          <EntityPanel
            key={w.principal_id}
            entityId={w.principal_id}
            onEntity={(id) => setSelection({ kind: "node", id })}
            onWindow={onWindow}
            windowIds={windowIds}
          />
        )}
      </Panel>
    </>
  );
}
